// Best-effort client-IP extraction from an inbound Next.js Request. Reads the
// usual proxy headers in order; falls back to "unknown" so downstream
// rate-limit keys always have a value.

export function clientIp(request: Request): string {
  const forwarded = request.headers.get('x-forwarded-for');
  if (forwarded) {
    const first = forwarded.split(',')[0]?.trim();
    if (first) {
      return first;
    }
  }
  const realIp = request.headers.get('x-real-ip');
  if (realIp) {
    return realIp;
  }
  return 'unknown';
}
